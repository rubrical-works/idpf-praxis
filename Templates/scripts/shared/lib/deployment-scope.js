/**
 * @framework-script 0.117.0
 * @description Classify files and commits by deployment scope (deployed vs dev-only).
 * Uses minimize-config.json rules, deployment chain awareness, and known path patterns.
 * Used by generate-changelog.js to separate user-facing from internal changes.
 * @checksum sha256:placeholder
 */

const fs = require('fs');
const path = require('path');

// --- Load minimize-config.json ---

let _config = null;

const EMPTY_CONFIG = { excludedCommands: [], excludedDirectories: [], includedDirectories: [] };

/**
 * Load minimize-config.json, recording whether it was actually found (#2602).
 *
 * The `loaded` flag is the whole point. This file lives under
 * `.claude/scripts/framework/`, which is dev-repo-only and never deployed, so in
 * a consuming project the read always fails and the empty-array substitution
 * used to be indistinguishable from a real config with nothing in it — every
 * path then fell through to a confident `dev-only`.
 *
 * @param {string} [configPath] - override; also bypasses the module cache, so
 *   tests can point at a fixture without poisoning subsequent calls
 * @returns {object} the config, plus a non-enumerable `loaded` boolean
 */
function loadConfig(configPath) {
    if (!configPath && _config) return _config;

    const resolved = configPath || path.resolve(__dirname, '../../framework/minimize-config.json');
    let result;
    try {
        result = { ...JSON.parse(fs.readFileSync(resolved, 'utf8')), loaded: true };
    } catch {
        result = { ...EMPTY_CONFIG, loaded: false };
    }

    if (!configPath) _config = result;
    return result;
}

/**
 * Deployed paths a consuming project declares for itself (#2602).
 *
 * The escape hatch for projects that have no minimize-config.json — which is
 * every project except this one. Read from `framework-config.json`
 * `deployedPaths`: a list of path prefixes that ship.
 *
 * @param {string} [projectRoot] - defaults to the current working directory,
 *   which is the consuming project when a symlinked helper runs inside it
 * @returns {string[]}
 */
function loadDeclaredPaths(projectRoot) {
    const root = projectRoot || process.cwd();
    try {
        const cfg = JSON.parse(fs.readFileSync(path.join(root, 'framework-config.json'), 'utf8'));
        return Array.isArray(cfg.deployedPaths) ? cfg.deployedPaths : [];
    } catch {
        return [];
    }
}

/**
 * Whether the classifier has anything to classify against.
 *
 * False means every answer outside the built-in patterns is a guess, and
 * `classifyFile` returns `'unknown'` rather than pretending otherwise.
 *
 * @param {{configPath?: string, projectRoot?: string}} [options]
 * @returns {boolean}
 */
function hasClassificationBasis(options = {}) {
    const config = loadConfig(options.configPath);
    // An empty deployedPaths array is not a declaration. Treating it as one
    // would quietly restore the confident dev-only this change removed.
    const declared = options.declaredPaths || loadDeclaredPaths(options.projectRoot);
    return Boolean(config.loaded) || declared.length > 0;
}

// --- The shared deployment path table (#3565) ---
//
// ONE table of known path patterns, read by two classifiers that ask two
// different questions — so a path can rightly get two different answers, and
// the table says which answer belongs to which question:
//
//   distribution — does the path reach the distribution repo? Asked by
//                  classifyFile() below, for generate-changelog.js.
//   userProject  — does the path reach a user project? Asked by
//                  review-repair.js classifyDeployPath(), for the Deployment
//                  Impact repair.
//
// Each answer is 'deployed', 'dev-only' or null — null means the table does
// not decide that question for the path and the classifier falls through to
// its own sources (minimize-config.json, project deployedPaths, or the
// manifest's deploymentFiles). Before #3565 each classifier kept its own list
// and the two disagreed silently on CHANGELOG.md and .claude/rules/.
const DEPLOYMENT_PATH_TABLE = Object.freeze([
    { pattern: /^tests\//, distribution: 'dev-only', userProject: 'dev-only', why: 'Test suites never ship.' },
    { pattern: /^\.claude\/rules\//, distribution: 'dev-only', userProject: null,
      why: 'Never deployed directly: self-hosted rules are synced from Reference/ via /fw-minimize-files (FRAMEWORK-ONLY preserved), and a user project\'s rules are generated by Praxis Hub Manager from the pre-stripped Reference/. Whether a rule reaches a user project is the manifest\'s deploymentFiles.rules call, not this table\'s.' },
    { pattern: /^\.github\//, distribution: 'dev-only', userProject: 'dev-only', why: 'CI workflows for this repo.' },
    { pattern: /^CLAUDE\.md$/, distribution: 'dev-only', userProject: 'dev-only', why: 'This repo\'s own instructions.' },
    { pattern: /^\.gh-pmu\.json$/, distribution: 'dev-only', userProject: 'dev-only', why: 'This repo\'s board configuration.' },
    { pattern: /^framework-config\.json$/, distribution: 'dev-only', userProject: 'dev-only', why: 'This repo\'s own config; a user project writes its own.' },
    { pattern: /^CHARTER\.md$/, distribution: 'dev-only', userProject: 'dev-only', why: 'This repo\'s charter.' },
    { pattern: /^Skills\/(?!Packaged\/)/, distribution: 'dev-only', userProject: null, why: 'Skill source dirs; Skills/Packaged/ is what ships.' },
    { pattern: /^Inception\//, distribution: 'dev-only', userProject: 'dev-only', why: 'Lifecycle documents for this repo.' },
    { pattern: /^Construction\//, distribution: 'dev-only', userProject: 'dev-only', why: 'Lifecycle documents for this repo.' },
    { pattern: /^Transition\//, distribution: 'dev-only', userProject: 'dev-only', why: 'Lifecycle documents for this repo.' },
    { pattern: /^\.claude\/scripts\/framework\//, distribution: null, userProject: 'dev-only',
      why: 'Maintainer scripts, never installed into a user project. The changelog has always counted them under .claude/scripts/ (deployed); not settled here.' },
    { pattern: /^Proposal\//, distribution: null, userProject: 'dev-only', why: 'Proposals never reach a user project; the changelog leaves them to minimize-config.json.' },
    { pattern: /^PRD\//, distribution: null, userProject: 'dev-only', why: 'PRDs never reach a user project; the changelog leaves them to minimize-config.json.' },
    { pattern: /^Archive\//, distribution: null, userProject: 'dev-only', why: 'Archived material never reaches a user project; the changelog leaves it to minimize-config.json.' },
    { pattern: /^\.claude\/scripts\//, distribution: 'deployed', userProject: null, why: 'Symlinked to user projects; which scripts is the manifest\'s call.' },
    { pattern: /^\.claude\/hooks\//, distribution: 'deployed', userProject: null, why: 'Symlinked to user projects; which hooks is the manifest\'s call.' },
    { pattern: /^\.claude\/metadata\//, distribution: 'deployed', userProject: null, why: 'Symlinked to user projects; which files is the manifest\'s call.' },
    { pattern: /^\.claude\/agents\/idpf\//, distribution: 'deployed', userProject: null, why: 'Framework agent definitions, junctioned into user projects (#3509).' },
    { pattern: /^Skills\/Packaged\//, distribution: 'deployed', userProject: null, why: 'Skill zip files ship.' },
    { pattern: /^framework-manifest\.json$/, distribution: 'deployed', userProject: null, why: 'Deployed as-is.' },
    { pattern: /^CHANGELOG\.md$/, distribution: 'deployed', userProject: 'dev-only',
      why: 'Ships in the distribution repo (its leads publish as release notes), but Praxis Hub Manager never places it in a user project — so the changelog counts it deployed and the Deployment Impact repair counts it dev-only. Both are right; they answer different questions.' },
    { pattern: /^LICENSE$/, distribution: 'deployed', userProject: null, why: 'Deployed as-is.' },
]);

const patternsWhere = (question, scope) => DEPLOYMENT_PATH_TABLE.filter((r) => r[question] === scope).map((r) => r.pattern);

// classifyFile()'s lists — the distribution question, derived from the table.
const DEV_ONLY_PATTERNS = patternsWhere('distribution', 'dev-only');
const DEPLOYED_PATTERNS = patternsWhere('distribution', 'deployed');

/**
 * Classify a single file path as 'deployed', 'dev-only' or 'unknown'.
 *
 * `'unknown'` is returned only when the path matched no built-in pattern AND
 * there was no basis to classify against (#2602) — no minimize-config.json and
 * no project-declared deployedPaths. It is deliberately distinguishable from
 * `'dev-only'`: a consuming project needs to be able to tell "this is internal"
 * from "the classifier did not apply here".
 *
 * @param {string} filePath - Relative file path from repo root
 * @param {{configPath?: string, projectRoot?: string, declaredPaths?: string[]}} [options]
 * @returns {'deployed'|'dev-only'|'unknown'}
 */
function classifyFile(filePath, options = {}) {
    const config = loadConfig(options.configPath);
    const declared = options.declaredPaths || loadDeclaredPaths(options.projectRoot);
    const normalized = filePath.replace(/\\/g, '/');

    // Check excluded commands first (most specific)
    if (config.excludedCommands && config.excludedCommands.includes(normalized)) {
        return 'dev-only';
    }

    // Check dev-only patterns
    for (const pattern of DEV_ONLY_PATTERNS) {
        if (pattern.test(normalized)) return 'dev-only';
    }

    // Check excluded directories
    if (config.excludedDirectories) {
        for (const dir of config.excludedDirectories) {
            if (normalized.startsWith(dir + '/') || normalized === dir) {
                return 'dev-only';
            }
        }
    }

    // Check deployed patterns
    for (const pattern of DEPLOYED_PATTERNS) {
        if (pattern.test(normalized)) return 'deployed';
    }

    // Check included directories (deployed via .min-mirror/)
    if (config.includedDirectories) {
        for (const dir of config.includedDirectories) {
            if (normalized.startsWith(dir + '/') || normalized === dir) {
                return 'deployed';
            }
        }
    }

    // Project-declared deployed paths — the escape hatch for a consuming
    // project, which has no minimize-config.json of its own (#2602).
    for (const dir of declared) {
        const prefix = dir.endsWith('/') ? dir : dir + '/';
        if (normalized.startsWith(prefix) || normalized === dir.replace(/\/$/, '')) {
            return 'deployed';
        }
    }

    // Nothing matched. Whether that means "internal" or "no idea" depends on
    // whether there was anything to match against (#2602).
    if (!config.loaded && declared.length === 0) return 'unknown';

    // Default: dev-only (unknown files are assumed internal)
    return 'dev-only';
}

/**
 * Classify a commit based on its changed files.
 *
 * A commit is 'deployed' if ANY of its files are deployed — unchanged. When
 * none are, it is 'unknown' if any file was unclassifiable, else 'dev-only'
 * (#2602). Deployed still wins outright: one shipped file makes the commit
 * user-facing whatever the rest were.
 *
 * An empty file list stays 'dev-only'. Nothing changed is not the same as
 * nothing classifiable, and reporting the empty case as unknown would flag
 * every merge commit.
 *
 * @param {string[]} files - Array of file paths changed in the commit
 * @param {{configPath?: string, projectRoot?: string, declaredPaths?: string[]}} [options]
 * @returns {'deployed'|'dev-only'|'unknown'}
 */
function classifyCommit(files, options = {}) {
    if (!files || files.length === 0) return 'dev-only';
    const scopes = files.map(f => classifyFile(f, options));
    if (scopes.includes('deployed')) return 'deployed';
    if (scopes.includes('unknown')) return 'unknown';
    return 'dev-only';
}

module.exports = { classifyFile, classifyCommit, hasClassificationBasis, DEPLOYMENT_PATH_TABLE };
